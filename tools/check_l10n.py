#!/usr/bin/env python3
"""Prüft die Lokalisierung von AETHER (läuft im Build und lokal ohne Xcode).

  python3 tools/check_l10n.py            prüfen
  python3 tools/check_l10n.py --write-en en.lproj aus den Schlüsseln im Code neu erzeugen

Regeln:
  * Jeder Schlüssel aus `tr("…")` im App-Code steht in de.lproj und en.lproj.
  * Platzhalter (%@, %ld, %d, %lld, %%) stimmen je Übersetzung in Art und Reihenfolge überein.
  * Keine verwaisten Einträge (Warnung).
"""
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SOURCES = ROOT / "Sources" / "AETHER"
LOC = ROOT / "Resources" / "Localization"
CALL = re.compile(r'\btr\(\s*"((?:[^"\\]|\\.)*)"')
SPEC = re.compile(r"%(?:\d+\$)?(?:@|ld|lld|d|lu|f|\.\df|%)")
ENTRY = re.compile(r'^\s*"((?:[^"\\]|\\.)*)"\s*=\s*"((?:[^"\\]|\\.)*)"\s*;\s*$')


def unescape(s: str) -> str:
    return s.replace('\\"', '"').replace("\\n", "\n").replace("\\\\", "\\")


def escape(s: str) -> str:
    return s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n")


def code_keys() -> dict:
    keys = {}
    for path in sorted(SOURCES.rglob("*.swift")):
        for match in CALL.finditer(path.read_text(encoding="utf-8")):
            key = unescape(match.group(1))
            keys.setdefault(key, str(path.relative_to(ROOT)))
    return keys


def read_strings(path: pathlib.Path) -> dict:
    table = {}
    if not path.exists():
        return table
    for number, line in enumerate(path.read_text(encoding="utf-8").splitlines(), 1):
        if not line.strip() or line.strip().startswith(("/*", "//", "*")):
            continue
        m = ENTRY.match(line)
        if not m:
            raise SystemExit(f"{path.name}:{number}: unlesbare Zeile: {line}")
        key, value = unescape(m.group(1)), unescape(m.group(2))
        if key in table:
            raise SystemExit(f"{path.name}:{number}: doppelter Schlüssel: {key}")
        table[key] = value
    return table


def specs(text: str) -> list:
    return [s.replace("lld", "ld") for s in SPEC.findall(text) if s != "%%"]


def main() -> int:
    keys = code_keys()
    if "--write-en" in sys.argv:
        out = LOC / "en.lproj" / "Localizable.strings"
        out.parent.mkdir(parents=True, exist_ok=True)
        lines = ["/* AETHER – English (development language). Generated by tools/check_l10n.py --write-en. */", ""]
        lines += [f'"{escape(k)}" = "{escape(k)}";' for k in sorted(keys, key=str.lower)]
        out.write_text("\n".join(lines) + "\n", encoding="utf-8")
        print(f"en.lproj: {len(keys)} Einträge geschrieben")

    problems = []
    warnings = []
    for language in ("en", "de"):
        table = read_strings(LOC / f"{language}.lproj" / "Localizable.strings")
        for key, where in keys.items():
            if key not in table:
                problems.append(f"[{language}] fehlt: {key!r} ({where})")
            elif specs(key) != specs(table[key]):
                problems.append(f"[{language}] Platzhalter passen nicht: {key!r} → {table[key]!r}")
            elif language == "de" and table[key].strip() == "":
                problems.append(f"[de] leer: {key!r}")
        for key in table:
            if key not in keys:
                warnings.append(f"[{language}] unbenutzt: {key!r}")

    for w in warnings:
        print("Warnung:", w)
    for p in problems:
        print("Fehler:", p)
    print(f"Lokalisierung: {len(keys)} Schlüssel im Code, {len(problems)} Fehler, {len(warnings)} Warnungen")
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
